def color_to_hex(name: str) -> str:
    """Подбирает HEX-код по названию цвета (регистронезависимо, по подстроке)."""
    n = name.strip().lower()
    for keyword, hexcode in COLOR_KEYWORDS:
        if keyword in n:
            return hexcode
    return "#B0A99F"  # нейтральный запасной цвет, если название не распознано


def _load_font(path: str, size: int):
    """Пытается загрузить нужный шрифт; если совсем ничего не найдено —
    использует встроенный шрифт PIL, чтобы функция не падала с ошибкой."""
    try:
        return ImageFont.truetype(path, size)
    except Exception:
        return ImageFont.load_default()


def _hex_to_rgb(h: str):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _luminance(rgb):
    r, g, b = [c / 255 for c in rgb]
    return 0.299 * r + 0.587 * g + 0.114 * b


def _text_color_for(bg_rgb):
    return (30, 30, 30) if _luminance(bg_rgb) > 0.6 else (255, 255, 255)


def generate_colors_image(colors_str: str) -> BytesIO:
    """
    Рисует простую картинку: только цветовые плашки и их названия —
    без заголовка, даты и подписи снизу. Строка вида
    "Песочный + бирюзовый + коралловый" -> 3 плашки с названиями.
    Возвращает готовый BytesIO (PNG) для reply_photo(photo=...).
    """
    label_font = _load_font(LABEL_FONT_PATH, 34)

    parts = [p.strip() for p in colors_str.split("+")]
    W, H = 1000, 420
    img = Image.new("RGB", (W, H), (255, 247, 240))
    draw = ImageDraw.Draw(img)

    margin, gap, top, swatch_h = 40, 24, 40, 340
    n = len(parts)
    swatch_w = (W - margin * 2 - gap * (n - 1)) // n

    for i, name in enumerate(parts):
        rgb = _hex_to_rgb(color_to_hex(name))
        x0 = margin + i * (swatch_w + gap)
        x1 = x0 + swatch_w
        y0, y1 = top, top + swatch_h
        draw.rounded_rectangle([x0, y0, x1, y1], radius=28, fill=rgb, outline=(230, 220, 210), width=2)

        tcolor = _text_color_for(rgb)
        words = name.split(" ")
        lines, cur = [], ""
        for w in words:
            test = (cur + " " + w).strip()
            if draw.textlength(test, font=label_font) > swatch_w - 24:
                lines.append(cur)
                cur = w
            else:
                cur = test
        if cur:
            lines.append(cur)

        total_h = len(lines) * 40
        ty = y0 + swatch_h // 2 - total_h // 2
        for ln in lines:
            tw = draw.textlength(ln, font=label_font)
            draw.text((x0 + swatch_w // 2 - tw // 2, ty), ln, font=label_font, fill=tcolor)
            ty += 40

    buf = BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    buf.name = "colors_of_the_day.png"
    return buf
